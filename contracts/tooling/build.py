"""Assemble A/B schema fragments into an offline, deterministic OpenAPI document."""

from __future__ import annotations

import copy
import json
from pathlib import Path
from urllib.parse import unquote

import yaml
from openapi_spec_validator import validate as validate_openapi

from contracts.validate import ROOT, UniqueKeyLoader, load_registry


class StableDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def assemble(root: Path = ROOT) -> dict:
    registry, documents = load_registry(root)
    resolver = registry.resolver()
    names = {}
    for uri, doc in documents.items():
        for name in doc["$defs"]:
            if name in names:
                raise ValueError(f"Duplicate public schema name: {name}")
            names[name] = f"{uri}#/$defs/{name}"

    def rewrite(value):
        if isinstance(value, list):
            return [rewrite(item) for item in value]
        if not isinstance(value, dict):
            return value
        if "$ref" in value:
            uri = value["$ref"]
            if "#/$defs/" not in uri:
                raise ValueError(f"Unsupported source reference: {uri}")
            prefix, suffix = uri.split("#/$defs/", 1)
            name, _, tail = suffix.partition("/")
            if prefix not in documents or names.get(name) != prefix + "#/$defs/" + name:
                raise ValueError(f"Unknown source reference: {uri}")
            if tail:
                # OpenAPI tools disagree about references into component properties.
                # Resolve deep schema pointers locally before code generation.
                target = copy.deepcopy(resolver.lookup(uri).contents)
                siblings = {key: item for key, item in value.items() if key != "$ref"}
                return rewrite({"allOf": [target, siblings]} if siblings else target)
            return {
                **{key: rewrite(item) for key, item in value.items() if key != "$ref"},
                "$ref": f"#/components/schemas/{unquote(name)}",
            }
        return {key: rewrite(item) for key, item in value.items()}

    components = {
        name: rewrite(copy.deepcopy(documents[uri.split("#", 1)[0]]["$defs"][name]))
        for name, uri in sorted(names.items())
    }
    paths = {}
    operation_ids = set()
    for path in sorted(root.glob("*/http.v1.yaml")):
        fragment = yaml.load(path.read_text(encoding="utf-8"), Loader=UniqueKeyLoader)
        if set(fragment) != {"paths"}:
            raise ValueError(f"HTTP fragment may only define paths: {path}")
        for url, item in fragment["paths"].items():
            target = paths.setdefault(url, {})
            for method, operation in item.items():
                if method in target:
                    raise ValueError(f"Duplicate path/method: {url} {method}")
                if method in {
                    "get",
                    "post",
                    "put",
                    "delete",
                    "patch",
                    "head",
                    "options",
                }:
                    identity = operation["operationId"]
                    if identity in operation_ids:
                        raise ValueError(f"Duplicate operationId: {identity}")
                    operation_ids.add(identity)
                target[method] = rewrite(operation)
    spec = {
        "openapi": "3.1.0",
        "info": {
            "title": "MLChess API contract review candidate",
            "version": "1.0.0",
            "description": "Proposed schema-first interface; routes are not implemented by this specification.",
        },
        "servers": [{"url": "/"}],
        "security": [{"SessionCookie": []}],
        "paths": dict(sorted(paths.items())),
        "components": {
            "securitySchemes": {
                "SessionCookie": {
                    "type": "apiKey",
                    "in": "cookie",
                    "name": "__Host-mlchess_session",
                    "description": "Opaque server-side account or limited guest session. Cookie naming is subject to auth configuration review.",
                }
            },
            "schemas": components,
        },
        "x-source-schemas": dict(sorted(names.items())),
        "x-websocket-schema": "https://mlchess.local/contracts/game/events.v1.yaml#/$defs/GameEventV1",
    }
    validate_openapi(spec)
    return spec


def render(spec: dict) -> str:
    return "# Generated by contracts/tooling/build.py. Do not edit.\n" + yaml.dump(
        spec, Dumper=StableDumper, sort_keys=False, width=100, allow_unicode=True
    )


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "openapi.generated.yaml")
    args = parser.parse_args()
    args.output.write_text(render(assemble()), encoding="utf-8")
    print(json.dumps({"output": str(args.output)}))
