"""Generate OpenAPI, Pydantic and TypeScript artifacts; --check never edits files."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from contracts.tooling.build import assemble, render
from contracts.validate import ROOT

OUTPUTS = (
    "contracts/openapi.generated.yaml",
    "backend/app/infra/generated/contracts.py",
    "contracts/generated/validation.schema.json",
    "contracts/generated/api.d.ts",
    "contracts/generated/fixtures.consumer.ts",
)


def python_projection(value):
    """Keep wire types; the original JSON Schema gate enforces semantic keywords."""
    if isinstance(value, list):
        return [python_projection(item) for item in value]
    if not isinstance(value, dict):
        return value
    dropped = {
        "format",
        "if",
        "then",
        "else",
        "not",
        "contains",
        "minContains",
        "maxContains",
    }
    if value.get("type") == "object" and "properties" in value:
        dropped.add("anyOf")
    output = {
        key: python_projection(item)
        for key, item in value.items()
        if key not in dropped
    }
    if "allOf" in output:
        output["allOf"] = [item for item in output["allOf"] if item]
        if not output["allOf"]:
            del output["allOf"]
    return output


def validation_bundle(spec):
    def rewrite(value):
        if isinstance(value, list):
            return [rewrite(item) for item in value]
        if not isinstance(value, dict):
            return value
        return {
            key: (
                item.replace("#/components/schemas/", "#/$defs/")
                if key == "$ref"
                else rewrite(item)
            )
            for key, item in value.items()
        }

    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://mlchess.local/contracts/generated/validation.schema.json",
        "$defs": rewrite(spec["components"]["schemas"]),
    }


def fixture_consumer(root):
    manifest = json.loads((root / "fixtures/manifest.json").read_text(encoding="utf-8"))
    lines = [
        "// Generated fixture/type compatibility examples. Do not edit.",
        'import type { components } from "./api.js";',
        "",
    ]
    for index, entry in enumerate(manifest):
        name = entry["schema"].rsplit("/", 1)[-1]
        payload = json.loads(
            (root / "fixtures" / entry["path"]).read_text(encoding="utf-8")
        )
        lines.extend(
            [
                f"// {entry['path']}",
                f'export const fixture{index} = {json.dumps(payload, indent=2, ensure_ascii=False)} satisfies components["schemas"]["{name}"];',
                "",
            ]
        )
    return "\n".join(lines)


def generate(root: Path = ROOT, *, check: bool = False) -> None:
    repo = root.parent
    spec = assemble(root)
    ts_cli = root / "node_modules/.bin/openapi-typescript"
    if not ts_cli.is_file():
        raise RuntimeError("Install pinned Node tools first: npm --prefix contracts ci")
    with tempfile.TemporaryDirectory(prefix="mlchess-contracts-") as folder:
        temp = Path(folder)
        for relative in OUTPUTS:
            (temp / relative).parent.mkdir(parents=True, exist_ok=True)
        (temp / OUTPUTS[0]).write_text(render(spec), encoding="utf-8")
        (temp / OUTPUTS[2]).write_text(
            json.dumps(validation_bundle(spec), indent=2) + "\n", encoding="utf-8"
        )
        projection = temp / "openapi.python.generated.json"
        projection.write_text(json.dumps(python_projection(spec)), encoding="utf-8")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(projection),
                "--input-file-type",
                "openapi",
                "--output",
                str(temp / OUTPUTS[1]),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.12",
                "--use-standard-collections",
                "--use-union-operator",
                "--enum-field-as-literal",
                "all",
                "--field-constraints",
                "--strict-nullable",
                "--extra-fields",
                "forbid",
                "--disable-timestamp",
                "--formatters",
                "black",
                "isort",
                "--custom-file-header",
                "# Generated by contracts/tooling/generate.py. Do not edit.",
            ],
            check=True,
            cwd=temp,
        )
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--no-cache",
                str(temp / OUTPUTS[1]),
            ],
            check=True,
            cwd=temp,
        )
        subprocess.run(
            [str(ts_cli), str(temp / OUTPUTS[0]), "-o", str(temp / OUTPUTS[3])],
            check=True,
            cwd=root,
        )
        (temp / OUTPUTS[4]).write_text(fixture_consumer(root), encoding="utf-8")
        stale = []
        for relative in OUTPUTS:
            expected = (temp / relative).read_bytes()
            target = repo / relative
            if check:
                if not target.is_file() or target.read_bytes() != expected:
                    stale.append(relative)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)
        if stale:
            raise RuntimeError("Generated artifacts differ: " + ", ".join(stale))
    print(
        "Generated artifacts are current."
        if check
        else "Generated all contract artifacts."
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(check=args.check)
