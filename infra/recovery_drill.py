"""Rehearse migrations and pg_dump/restore using two disposable local databases.

The existing application database is never read or changed. Only databases with
names generated by this invocation are created and removed. No backup secrets or
game data leave the PostgreSQL container except the synthetic in-memory archive.
"""

from __future__ import annotations

import argparse
import io
import json
import re
import subprocess
import time
from uuid import uuid4

import chess
from alembic import command
from alembic.config import Config


def migration_sql() -> str:
    output = io.StringIO()
    config = Config("backend/alembic.ini", output_buffer=output)
    config.set_main_option("sqlalchemy.url", "postgresql+asyncpg://unused/unused")
    command.upgrade(config, "head", sql=True)
    return output.getvalue()


def seed_sql() -> str:
    white, black, game_id = (str(uuid4()) for _ in range(3))
    rows = [
        f"INSERT INTO users(id,kind,created_at) VALUES ('{white}','account',now()),"
        f"('{black}','account',now());"
    ]
    board = chess.Board()
    moves = []
    for ply, uci in enumerate(("f2f3", "e7e5", "g2g4", "d8h4"), 1):
        move = chess.Move.from_uci(uci)
        san = board.san(move)
        actor = white if board.turn else black
        board.push(move)
        moves.append(
            "INSERT INTO game_moves(id,game_id,actor_id,client_move_id,"
            "expected_version,version,ply,revision,uci,san,fen_after,created_at) "
            f"VALUES ('{uuid4()}','{game_id}','{actor}','{uuid4()}',"
            f"{ply - 1},{ply},{ply},0,'{uci}','{san}','{board.fen()}',now());"
        )
    assert board.is_checkmate() and board.outcome().winner == chess.BLACK
    rows.append(
        "INSERT INTO games(id,mode,status,version,revision,fen,ply,side_to_move,"
        "result,termination,created_at,updated_at) "
        f"VALUES ('{game_id}','friend','finished',4,0,'{board.fen()}',4,"
        "'white','black','checkmate',now(),now());"
    )
    for side, actor in (("white", white), ("black", black)):
        rows.append(
            "INSERT INTO game_players(game_id,side,kind,user_id,joined_at) "
            f"VALUES ('{game_id}','{side}','human','{actor}',now());"
        )
    rows.extend(moves)
    rows.append(
        "INSERT INTO outbox_events(id,aggregate_type,aggregate_id,event_type,"
        "payload,attempts,created_at) "
        f"VALUES ('{uuid4()}','game','{game_id}','game.status_changed',"
        '\'{"result":"black"}\',0,now());'
    )
    return "BEGIN;\n" + "\n".join(rows) + "\nCOMMIT;"


FINGERPRINT = """
SELECT json_build_object(
  'schema', (SELECT version_num FROM alembic_version),
  'users', (SELECT count(*) FROM users),
  'games', (SELECT count(*) FROM games),
  'fen', (SELECT fen FROM games),
  'result', (SELECT result FROM games),
  'moves', (SELECT string_agg(uci, ',' ORDER BY ply) FROM game_moves),
  'pending_outbox', (SELECT count(*) FROM outbox_events WHERE published_at IS NULL)
);
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--container", default="mlchess-postgres")
    parser.add_argument("--user", default="mlchess")
    args = parser.parse_args()
    if any(
        not re.fullmatch(r"[A-Za-z0-9_.-]+", v) for v in (args.container, args.user)
    ):
        parser.error("container and user must be simple Docker/PostgreSQL names")
    databases = ["mlchess_drill_" + uuid4().hex for _ in range(2)]
    created: list[str] = []

    def run(*argv: str, data: bytes | None = None) -> bytes:
        return subprocess.run(
            ["docker", "exec", "-i", args.container, *argv],
            input=data,
            capture_output=True,
            check=True,
            timeout=60,
        ).stdout

    def sql(database: str, statement: str) -> bytes:
        return run(
            "psql",
            "-X",
            "-qAt",
            "-v",
            "ON_ERROR_STOP=1",
            "-U",
            args.user,
            "-d",
            database,
            data=statement.encode(),
        )

    try:
        for database in databases:
            run("createdb", "-U", args.user, database)
            created.append(database)
        source, target = databases
        sql(source, migration_sql())
        sql(source, seed_sql())
        before = json.loads(sql(source, FINGERPRINT))
        started = time.monotonic()
        archive = run("pg_dump", "-U", args.user, "-Fc", source)
        backup_seconds = time.monotonic() - started
        started = time.monotonic()
        run(
            "pg_restore",
            "-U",
            args.user,
            "--no-owner",
            "--no-privileges",
            "--exit-on-error",
            "-d",
            target,
            data=archive,
        )
        restore_seconds = time.monotonic() - started
        after = json.loads(sql(target, FINGERPRINT))
        if before != after or after["pending_outbox"] != 1:
            raise RuntimeError("Restored game/history/outbox differs from source")
        print(
            json.dumps(
                {
                    "status": "passed",
                    "scope": "synthetic local PostgreSQL drill, not production RPO/RTO",
                    "backup_seconds": round(backup_seconds, 3),
                    "restore_seconds": round(restore_seconds, 3),
                    "archive_bytes": len(archive),
                    "restored": after,
                    "pending_outbox_survived": True,
                    "worker_redis_redispatch_verified": False,
                },
                indent=2,
            )
        )
        return 0
    finally:
        # Exact generated names only; never accept a cleanup target from the CLI.
        for database in reversed(created):
            run("dropdb", "-U", args.user, database)


if __name__ == "__main__":
    raise SystemExit(main())
